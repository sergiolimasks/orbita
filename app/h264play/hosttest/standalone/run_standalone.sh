#!/usr/bin/env bash
# XCloud360 stage 5 — offline E2E of the integrated Xbox-only path:
# menu (menu_model) -> xc_native -> session thread (xs_machine over a fake
# GSSV) + WebRTC (xc_webrtc via the xsm mailbox) <-> pion "xCloud" over
# loopback UDP. NO real xCloud, no real tokens, never ports 9000-9004.
#
#   run_standalone.sh [host|ppc] [seconds of game per session, default 12]
#
# ppc = ppc32 big-endian build under qemu (Xenon byte order).
# XCW_LOSS=0.03 [XCW_LOSS_ONCE=1]: drop incoming video RTP before SRTP
# (NACK repair + the NACK-based RTT estimate in the STAT line).
# Then hosttest/webrtc/check_e2e.py judges each streamed session (s1, s3)
# and check_pads.py the multi-controller part.
# v0.19.2: the fake GSSV is a local TLS 1.2 server (port_rt.c) and the app's
# real https.c talks to it (keep-alive, resumption, non-blocking hw1 path).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP="$(cd "$HERE/../.." && pwd)"
REPO="$(cd "$APP/../.." && pwd)"
T="${1:-host}"
S="${2:-12}"
H264="${H264:-$REPO/tools/xcloud-capture/output/GOLDEN-synth-720p60-baseline-5s/stream.h264}"
W="${OUTROOT:-$HOME/webrtc-xenon}"
GO="$W/tools/go/bin/go"
export GOPATH="$W/tools/gopath" GOMODCACHE="$W/tools/gopath/pkg/mod" GOFLAGS=-mod=mod
[[ -f "$W/$T/lib/libpeer-xc.a" ]] || "$REPO/deps/webrtc-xenon/build.sh" "$T"
PION="$W/tools/peer_pion"
if [[ ! -x "$PION" || "$APP/hosttest/webrtc/peer_pion/main.go" -nt "$PION" ]]; then
  (cd "$APP/hosttest/webrtc/peer_pion" && "$GO" mod tidy >/dev/null 2>&1 && "$GO" build -o "$PION" .)
fi

OUT="$W/$T/test"
mkdir -p "$OUT"
# v0.19.2: throw-away CA + server cert (SANs = every host the app talks to)
# for the local TLS fake GSSV; the CA is the app's only embedded root here.
TLS="$OUT/tls"
mkdir -p "$TLS"
if [[ ! -f "$TLS/srv.crt" ]] || [[ -n "$(find "$TLS/srv.crt" -mmin +1200)" ]]; then
  openssl req -x509 -newkey rsa:2048 -nodes -keyout "$TLS/ca.key" -out "$TLS/ca.crt" -days 3 \
    -subj "/CN=XCloud360 E2E test CA" -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
  openssl req -newkey rsa:2048 -nodes -keyout "$TLS/srv.key" -out "$TLS/srv.csr" -subj "/CN=fake-gssv" 2>/dev/null
  {
    echo "subjectAltName=DNS:brs.core.gssv-play-prod.xboxlive.com,DNS:*.gssv-play-prod.xboxlive.com,DNS:login.microsoftonline.com,DNS:user.auth.xboxlive.com,DNS:xsts.auth.xboxlive.com,DNS:login.live.com"
    echo "extendedKeyUsage=serverAuth"
    echo "basicConstraints=CA:FALSE"
  } > "$TLS/ext.cnf"
  openssl x509 -req -in "$TLS/srv.csr" -CA "$TLS/ca.crt" -CAkey "$TLS/ca.key" -CAcreateserial -days 2 \
    -extfile "$TLS/ext.cnf" -out "$TLS/srv.crt" 2>/dev/null
fi
{
  echo "/* generated by run_standalone.sh: the E2E test CA */"
  echo "const char xc_ca_roots_pem[] ="
  sed 's/^/"/; s/$/\\n"/' "$TLS/ca.crt"
  echo ";"
} > "$TLS/ca_test.c"

SRC="$APP/source"
case "$T" in
  host) CC=gcc; FLAGS="-O1 -g -Wall -Wextra -Wno-unused-parameter -Wno-sign-compare -fsanitize=address,undefined -fno-sanitize-recover=undefined"; RUN="" ;;
  ppc)  source "$HOME/scratch/wf/ppc-tools/env-ppc.sh"
        CC="$PPC_CC"; FLAGS="-O2 -g -Wall -m32 -mcpu=7450 -mno-altivec --sysroot=$PPC_SYSROOT -static"; RUN="$QEMU_PPC -cpu 7450" ;;
  *) echo "target?"; exit 2 ;;
esac
DEFS="-DMBEDTLS_CONFIG_FILE=\"xc360_mbedtls_webrtc_config.h\""
INC="$DEFS -I$SRC/webrtc -I$W/$T/include -I$SRC/session -I$SRC/login -I$SRC"
LIBS="-L$W/$T/lib -lpeer-xc -lusrsctp-xc -lsrtp2-xc -lmbedtls-xcwebrtc -lpthread -lm"
$CC $FLAGS $INC -o "$OUT/standalone_e2e" \
    "$HERE/standalone_e2e.c" "$HERE/port_rt.c" "$HERE/xs_task_posix.c" \
    "$SRC/native/xc_native.c" "$SRC/menu_model.c" \
    "$SRC/session/xc_session.c" "$SRC/session/xs_machine.c" "$SRC/login/xbox_auth.c" "$SRC/login/cjson/cJSON.c" \
    "$SRC/login/https.c" "$SRC/login/http_parse.c" "$TLS/ca_test.c" \
    "$SRC/webrtc/xc_webrtc.c" "$SRC/webrtc/xc_webrtc_xsm.c" "$SRC/webrtc/xc_jitter.c" "$SRC/webrtc/xc_proto.c" \
    "$APP/hosttest/webrtc/xc_udp_posix.c" $LIBS

RUNDIR="$W/e2e/standalone-$T-$(date +%H%M%S)"
mkdir -p "$RUNDIR"
echo "=== standalone E2E $T, ${S}s per game -> $RUNDIR"
set +e
XCW_LOSS_AFTER="${XCW_LOSS_AFTER:-300}" ASAN_OPTIONS=detect_leaks=0 $RUN "$OUT/standalone_e2e" --dir "$RUNDIR" --pion "$PION" --h264 "$H264" --seconds "$S" \
    --cert "$TLS/srv.crt" --key "$TLS/srv.key" \
    > "$RUNDIR/app.out" 2> "$RUNDIR/app.log"
RC=$?
set -e
grep -E "^=== |FAIL |first AU|teardown|gssv:|STAT tail|B pressed|\[menu\]|### |tls region|decoder opened|>>>|\[dec\]|handshake lines|\[tls-srv\] .*close" "$RUNDIR/app.log" || true
grep -E "LOG \[tls\] (brs|conexao)|LOG \[sess\] (hw1|fase .*entregue)|LOG \[xn\] (thread da sessao de volta|sessao esperando)" "$RUNDIR/app.log" | cut -c1-200 | head -40 || true
cat "$RUNDIR/app.out"
V=0
for s in s1 s3; do
  echo "--- check_e2e $s"
  python3 "$APP/hosttest/webrtc/check_e2e.py" "$RUNDIR/$s" "${XCW_LOSS:-0}" | grep -E "^(video|audio|setup|rtp|rtcp|dc|input|rtt|VERDICT)" || V=1
  python3 "$HERE/check_pads.py" "$RUNDIR/$s" "${XCW_LOSS:-0}" || V=1
done
[[ $RC -eq 0 && $V -eq 0 ]] && echo "STANDALONE VERDICT: PASS ($RUNDIR)" || { echo "STANDALONE VERDICT: FAIL ($RUNDIR)"; exit 1; }
