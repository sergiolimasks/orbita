/*
 * XCloud360 v0.18 — generates the Opus test stream embedded in the ELF
 * (source/audio/aud_tone_stream.c) and the same packets as a .pkts file for
 * the host test. Encoded like xCloud sends it: CELT-only (RESTRICTED_LOWDELAY),
 * 48 kHz stereo, 20 ms, 64 kbps.
 *
 * 4.4 s, played in a loop by the X ("teste offline") test:
 *   0.0-0.8  440 Hz, LEFT only     -> confirms channel order
 *   0.8-1.6  660 Hz, RIGHT only
 *   1.6-1.8  silence
 *   1.8-3.8  log sweep 100 Hz -> 8 kHz, both channels
 *   3.8-4.0  silence
 *   4.0-4.4  3 short 880 Hz beeps, both
 * Wrong byte order on the Xbox = loud white noise instead of any of this.
 *
 * usage: gen_tone out.c out.pkts
 */
#include <math.h>
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <opus.h>

#define SR 48000
#define FR 960
#define DUR_FRAMES 220      /* 4.4 s */
#define AMP 0.30            /* -10.5 dBFS */

static double env(double t, double a, double b) {   /* 5 ms ramps, no clicks */
    if (t < a || t >= b) return 0;
    double r = 0.005, e = 1;
    if (t - a < r) e = (t - a) / r;
    if (b - t < r) e = (b - t) / r;
    return e;
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s out.c out.pkts\n", argv[0]); return 2; }
    int err;
    OpusEncoder *enc = opus_encoder_create(SR, 2, OPUS_APPLICATION_RESTRICTED_LOWDELAY, &err);
    if (err != OPUS_OK) return 1;
    opus_encoder_ctl(enc, OPUS_SET_BITRATE(64000));
    opus_encoder_ctl(enc, OPUS_SET_COMPLEXITY(10));
    opus_encoder_ctl(enc, OPUS_SET_VBR(1));
    FILE *fc = fopen(argv[1], "w"), *fp = fopen(argv[2], "wb");
    if (!fc || !fp) return 1;
    fprintf(fc, "/* AUTO-GENERATED by hosttest/audio/gen_tone.c (libopus %s) — do not edit.\n"
                " * Opus CELT 48 kHz stereo 20 ms, %d packets: [u16 BE len][payload] ... */\n"
                "#include <stddef.h>\n#include <stdint.h>\n"
                "const uint8_t aud_tone_stream[] = {\n", opus_get_version_string(), DUR_FRAMES);
    double ph_l = 0, ph_r = 0, ph_s = 0;
    long total = 0;
    int col = 0;
    for (int f = 0; f < DUR_FRAMES; f++) {
        int16_t pcm[FR * 2];
        for (int i = 0; i < FR; i++) {
            double t = (f * FR + i) / (double)SR;
            double l = 0, r = 0;
            l += AMP * env(t, 0.0, 0.8) * sin(ph_l);
            r += AMP * env(t, 0.8, 1.6) * sin(ph_r);
            if (t >= 1.8 && t < 3.8) {
                double k = (t - 1.8) / 2.0, fq = 100.0 * pow(80.0, k);
                double s = AMP * env(t, 1.8, 3.8) * sin(ph_s);
                l += s; r += s;
                ph_s += 2 * M_PI * fq / SR;
            }
            for (int bp = 0; bp < 3; bp++) {
                double a = 4.0 + bp * 0.13;
                double s = AMP * env(t, a, a + 0.08) * sin(2 * M_PI * 880 * t);
                l += s; r += s;
            }
            ph_l += 2 * M_PI * 440 / SR;
            ph_r += 2 * M_PI * 660 / SR;
            pcm[2 * i] = (int16_t)lrint(l * 32767);
            pcm[2 * i + 1] = (int16_t)lrint(r * 32767);
        }
        unsigned char pkt[1500];
        int n = opus_encode(enc, pcm, FR, pkt, sizeof(pkt));
        if (n <= 0) { fprintf(stderr, "encode failed %d\n", n); return 1; }
        uint8_t h[8] = { (uint8_t)(n >> 8), (uint8_t)n, (uint8_t)(f >> 8), (uint8_t)f,
                         (uint8_t)((f * FR) >> 24), (uint8_t)((f * FR) >> 16),
                         (uint8_t)((f * FR) >> 8), (uint8_t)(f * FR) };
        fwrite(h, 1, 8, fp);
        fwrite(pkt, 1, (size_t)n, fp);
        uint8_t lh[2] = { h[0], h[1] };
        for (int k = 0; k < n + 2; k++) {
            int v = k < 2 ? lh[k] : pkt[k - 2];
            fprintf(fc, "%s0x%02x,", col == 0 ? "  " : "", v);
            if (++col == 16) { fputc('\n', fc); col = 0; }
        }
        total += n + 2;
    }
    fprintf(fc, "%s};\nconst size_t aud_tone_stream_len = %ld;\nconst int aud_tone_stream_pkts = %d;\n",
            col ? "\n" : "", total, DUR_FRAMES);
    fclose(fc);
    fclose(fp);
    opus_encoder_destroy(enc);
    fprintf(stderr, "gen_tone: %d packets, %ld bytes\n", DUR_FRAMES, total);
    return 0;
}
